-- Minimal Creator record so creator deep links can be resolved (US-005).
-- The creator profile (bio, persona, price, ...) arrives with Phase B. The link between a creator and a
-- CREATOR-role user is enforced transactionally by the approval flow (backend rule 9), not in SQL.

-- CreateEnum
CREATE TYPE "CreatorStatus" AS ENUM ('ACTIVE', 'BLOCKED');

-- CreateTable
CREATE TABLE "creators" (
    "id" UUID NOT NULL DEFAULT gen_random_uuid(),
    "user_id" UUID NOT NULL,
    "public_code" TEXT NOT NULL,
    "status" "CreatorStatus" NOT NULL DEFAULT 'ACTIVE',
    "created_at" TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updated_at" TIMESTAMPTZ(3) NOT NULL,

    CONSTRAINT "creators_pkey" PRIMARY KEY ("id")
);

